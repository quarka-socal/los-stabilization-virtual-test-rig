const { chromium } = require('playwright-core');
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell', args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
  const errs = [];
  page.on('pageerror', e => errs.push('pageerror: ' + e.message + ' @ ' + (e.stack || '').split('\n').slice(1, 3).join(' | ')));
  page.on('console', m => { if (m.type() === 'error' && !/ERR_TUNNEL|Failed to load resource/.test(m.text())) errs.push('console: ' + m.text()); });
  await page.goto('http://127.0.0.1:8765/test.html#duzenek', { waitUntil: 'load' });
  await page.waitForTimeout(1200);
  await page.click('#tab-model'); await page.waitForTimeout(300);
  await page.evaluate(() => { for (const d of document.querySelectorAll('details.pgroup')) if (d.textContent.includes('Dünya dönüşü')) d.open = true; });
  await page.click('[id="p-wb.earth.comp"]'); await page.waitForTimeout(600);
  console.log('earth panel:', await page.evaluate(() => document.querySelector('#mEarth p:nth-child(2)').textContent));
  await page.screenshot({ path: __dirname + '/shots/10_model_earth.png', clip: { x: 760, y: 0, width: 680, height: 1000 } });
  await page.click('#tab-duzenek');
  await page.waitForFunction(() => /dünya dönüşü kompanzasyonu kapalı/.test(document.querySelector('#pstat').textContent), null, { timeout: 60000 });
  console.log('pstat:', await page.evaluate(() => document.querySelector('#pstat').textContent));
  await page.waitForTimeout(1500);
  await page.evaluate(() => { const s = document.querySelector('#scrub'); s.value = 55; s.dispatchEvent(new Event('input')); });
  await page.waitForTimeout(500);
  console.log('metrics:', await page.evaluate(() => document.querySelector('#pmet').innerText.replace(/\n/g, ' | ').slice(0, 700)));
  await page.screenshot({ path: __dirname + '/shots/11_duzenek_compoff.png' });
  await page.click('#tab-kampanya'); await page.waitForTimeout(300);
  await page.click('#ti-T1_1'); await page.waitForTimeout(200); await page.click('#runOne');
  await page.waitForFunction(() => !document.querySelector('#runAll').disabled, null, { timeout: 300000 });
  await page.waitForTimeout(500);
  console.log('T1.1 pill:', await page.evaluate(() => document.querySelector('#ti-T1_1 .pill').textContent));
  console.log('T1.1 measured:', await page.evaluate(() => document.querySelector('.measured').textContent.slice(0, 260)));
  console.log('T1.1 first note:', await page.evaluate(() => (document.querySelector('.notes li') || {}).textContent));
  await page.screenshot({ path: __dirname + '/shots/12_t11_invalid.png' });
  console.log('ERRORS:', errs.length ? errs.join('\n') : 'none');
  await browser.close();
})().catch(e => { console.error('FAILED', e); process.exit(1); });
